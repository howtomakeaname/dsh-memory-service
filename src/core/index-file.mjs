import fs from "node:fs";
import path from "node:path";

export function renderMemoryIndex(notes) {
  const lines = ["# Memory", "", "Generated by dsh-memory-service. Edit notes, not this file.", ""];
  for (const note of notes) lines.push("- [" + note.title + "](" + note.id + ".md) — " + (note.description || ""));
  return lines.join("\n") + "\n";
}

export function writeMemoryIndex(dir, notes) {
  fs.writeFileSync(path.join(dir, "MEMORY.md"), renderMemoryIndex(notes));
}
