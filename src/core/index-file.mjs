import fs from "node:fs";
import path from "node:path";

export const INDEX_MAX_LINES = 200;
export const INDEX_MAX_BYTES = 25000;

export function renderMemoryIndex(notes, { maxLines = INDEX_MAX_LINES, maxBytes = INDEX_MAX_BYTES } = {}) {
  const lines = ["# Memory Index", "", "Generated by dsh-memory-service. Edit notes, not this file.", ""];
  let skipped = 0;
  for (const note of notes) {
    const line = "- [" + note.title + "](" + note.id + ".md) — " + (note.description || "");
    const next = [...lines, line];
    if (next.length > maxLines || Buffer.byteLength(next.join("\n") + "\n") > maxBytes) {
      skipped += 1;
      continue;
    }
    lines.push(line);
  }
  if (skipped > 0) {
    const warningFor = (n) => "> WARNING: " + n + " more memories omitted from this index; move detail into topic files or prune stale entries.";
    while (lines.length > 4 && (lines.length >= maxLines || Buffer.byteLength([...lines, warningFor(skipped)].join("\n") + "\n") > maxBytes)) { lines.pop(); skipped += 1; }
    const warning = warningFor(skipped);
    if (Buffer.byteLength([...lines, warning].join("\n") + "\n") <= maxBytes) lines.push(warning);
  }
  return lines.join("\n") + "\n";
}

export function writeMemoryIndex(dir, notes, options) {
  fs.writeFileSync(path.join(dir, "MEMORY.md"), renderMemoryIndex(notes, options));
}
